import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync(new URL('./public/app.js',import.meta.url),'utf8').split('let state,corrupt=false;')[0];
const ctx=vm.createContext({URL,document:{querySelector(){},querySelectorAll(){return []}},crypto:{randomUUID:()=> 'test'}});
vm.runInContext(source,ctx);
const run=code=>vm.runInContext(code,ctx);
assert.equal(run('validate(seed()).items.length'),9);
assert.equal(run("safeURL('javascript:alert(1)')"),'');
assert.equal(run("safeURL('https://example.com')"),'https://example.com/');
assert.equal(run("safeImage('data:image/svg+xml,<svg onload=alert(1)>')"),'');
assert.equal(run("esc('<img src=x onerror=alert(1)>')"),'&lt;img src=x onerror=alert(1)&gt;');
assert.throws(()=>run('validate({version:1,worlds:[],items:[]})'));
assert.throws(()=>run("(()=>{const v=seed();v.items[0].world='missing';validate(v)})()"));
assert.throws(()=>run('(()=>{const v=seed();v.items.push(v.items[0]);validate(v)})()'));
assert.throws(()=>run("(()=>{const v=seed();v.worlds[0].color='red; color:blue';validate(v)})()"));
assert.throws(()=>run("(()=>{const v=seed();v.items[0].image='x'.repeat(1600001);validate(v)})()"));
assert.equal(run('(()=>{const v=seed();v.items[0].x=-400;return validate(v).items[0].x})()'),10);
console.log('11 data checks passed: seed, URLs, escaping, backup validation, limits.');
